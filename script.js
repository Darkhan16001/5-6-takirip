function showPage(index) {
  if (index < 0 || index >= pages.length) {
    return;
  }

  currentStage = index;

  // Бет ауысқанда ескі видео тоқтайды,
  // өйткені iframe беттен алынып тасталады.

  document.getElementById("content").innerHTML =
    pages[index]();

  document.getElementById("stageTitle").textContent =
    stages[index].name;

  document.getElementById("pageCount").textContent =
    `${index + 1} / ${pages.length}`;

  document.getElementById("progressBar").style.width =
    ((index + 1) / pages.length * 100) + "%";

  const previous = document.getElementById("previous");
  const next = document.getElementById("next");

  previous.disabled = index === 0;
  next.disabled = index === pages.length - 1;

  next.textContent =
    index === pages.length - 2
      ? "Қорытындыға өту →"
      : "Келесі бет →";

  renderNavigation();

  if (index === 5) {
    const input = document.getElementById("studentNames");

    if (input) {
      input.value = studentNamesText;
    }
  }

  if (index === 6) {
    refreshAwardButtons();
  }

  if (index === 7) {
    renderFinalScores();
  }

  window.scrollTo({
    top: 0,
    behavior: "smooth"
  });
}

