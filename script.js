// 2. ТАЙМЕР
// =============================================

const TOTAL_MS = TOTAL_MINUTES * 60000;

let elapsedBeforeStart = 0;
let startedAt = null;
let timerInterval = null;

function getElapsed() {
  if (startedAt === null) {
    return elapsedBeforeStart;
  }

  return elapsedBeforeStart + Date.now() - startedAt;
}

function formatTime(ms) {
  const seconds = Math.floor(ms / 1000);
  const minutes = Math.floor(seconds / 60);

  return (
    String(minutes).padStart(2, "0") +
    ":" +
    String(seconds % 60).padStart(2, "0")
  );
}

function updateTimer() {
  const elapsed = Math.min(getElapsed(), TOTAL_MS);
  const remaining = Math.max(TOTAL_MS - elapsed, 0);

  document.getElementById("timer").textContent =
    formatTime(elapsed);

  document.getElementById("remaining").textContent =
    remaining > 0
      ? "Қалғаны: " + formatTime(remaining)
      : "80 минут аяқталды";

  if (elapsed >= TOTAL_MS && startedAt !== null) {
    pauseTimer();
  }
}

function startTimer() {
  if (startedAt !== null) return;

  if (elapsedBeforeStart >= TOTAL_MS) {
    elapsedBeforeStart = 0;
  }

  startedAt = Date.now();

  timerInterval = setInterval(updateTimer, 500);
  updateTimer();
}

function pauseTimer() {
  if (startedAt === null) return;

  elapsedBeforeStart = Math.min(
    getElapsed(),
    TOTAL_MS
  );

  startedAt = null;

  clearInterval(timerInterval);
  timerInterval = null;

  updateTimer();
}

function resetTimer() {
  pauseTimer();
  elapsedBeforeStart = 0;
  updateTimer();
}

document.getElementById("startTimer")
  .addEventListener("click", startTimer);

document.getElementById("pauseTimer")
  .addEventListener("click", pauseTimer);

document.getElementById("resetTimer")
  .addEventListener("click", resetTimer);

