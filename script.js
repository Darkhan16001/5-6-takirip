document.addEventListener("click", function(event) {

  // Кезеңді таңдау
  const stageButton =
    event.target.closest("[data-stage]");

  if (stageButton) {
    showPage(Number(stageButton.dataset.stage));
    return;
  }

  // Жауапты көрсету / жасыру
  const revealButton =
    event.target.closest("[data-reveal]");

  if (revealButton) {
    const id = revealButton.dataset.reveal;
    const answer = document.getElementById(id);

    if (!answer) return;

    answer.classList.toggle("visible");

    revealButton.textContent =
      answer.classList.contains("visible")
        ? "Жауапты жасыру"
        : "Жауабын көрсету";

    return;
  }

  // Ұпай қосу / қайтарып алу
  const awardControl =
    event.target.closest("[data-award]");

  if (awardControl) {
    const [team, key, points] =
      awardControl.dataset.award.split("|");

    toggleAward(
      Number(team),
      key,
      Number(points)
    );

    return;
  }

  // Кездейсоқ студент
  if (event.target.closest("#pickStudent")) {
    pickStudent();
    return;
  }

  // Сайт ішінде видеоны қосу
  if (event.target.closest("#playEmbedded")) {
    playEmbeddedVideo();
    return;
  }

  // Видео ойнатқышын жабу
  if (event.target.closest("#closeEmbedded")) {
    const container =
      document.getElementById("videoContainer");

    if (container) {
      showPage(3);
    }

    return;
  }
});

