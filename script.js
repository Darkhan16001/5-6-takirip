// Әр тапсырмаға ұпай бір рет беріледі.
// Батырма екінші рет басылса, ұпай қайтарылады.

const awarded = [{}, {}, {}];

function teamScore(index) {
  return Object.values(awarded[index]).reduce(
    (sum, points) => sum + points,
    0
  );
}

function updateScoreboard() {
  const scoreboard = document.getElementById("scoreboard");

  scoreboard.innerHTML = awarded.map((_, index) => `
    <div class="score-row">
      <span>${index + 1}-команда</span>
      <strong>${teamScore(index)} ұпай</strong>
    </div>
  `).join("");

  if (currentStage === 7) {
    renderFinalScores();
  }
}

function awardButton(team, key, points) {
  const active = Boolean(awarded[team][key]);

  return `
    <button
      class="award ${active ? "active" : ""}"
      data-award="${team}|${key}|${points}"
    >
      ${active ? "✓ Ұпай берілді" : "+" + points + " ұпай"}
    </button>
  `;
}

function refreshAwardButtons() {
  document.querySelectorAll("[data-award]")
    .forEach(button => {
      const [team, key, points] =
        button.dataset.award.split("|");

      const active = Boolean(
        awarded[Number(team)][key]
      );

      button.textContent = active
        ? "✓ Ұпай берілді"
        : "+" + points + " ұпай";

      button.classList.toggle("active", active);
    });
}

function toggleAward(team, key, points) {
  if (!awarded[team]) return;

  if (awarded[team][key]) {
    delete awarded[team][key];
  } else {
    awarded[team][key] = points;
  }

  refreshAwardButtons();
  updateScoreboard();
}

function resetScores() {
  if (!confirm("Барлық ұпайды нөлдейміз бе?")) {
    return;
  }

  awarded.forEach(team => {
    Object.keys(team).forEach(key => {
      delete team[key];
    });
  });

  refreshAwardButtons();
  updateScoreboard();
}

document.getElementById("resetScores")
